/**
 * The per-symbol trading plan — which of the robot's permitted symbols the
 * user actually wants, at what size, and how many at once.
 *
 * ## Why this exists at all
 *
 * `sync-symbol-config`'s own docstring says the plan "has to exist somewhere
 * the executor can read it: broker-execute applies it as a ceiling before
 * placing any order, because a cap kept only on the handset is a cap that a
 * stale, rolled-back or modified client silently ignores."
 *
 * Android has posted there since its Trading Symbols rewrite. **iOS never
 * has.** The old PairsView rendered `lot: 0.10, maxTrades: 3` as hardcoded
 * literals, showed a P/L figure generated by `Math.random()`, and its Save
 * button closed the accordion without writing anything — to the server or to
 * disk. Every cap an iOS user set was fiction.
 *
 * ## Local plan, server ceiling
 *
 * The plan is held device-local (like the theme prefs) and pushed on change.
 * There is no read-back endpoint: `sync-symbol-config` is POST-and-upsert, and
 * a direct table read is not available to an app install, which holds a
 * mentor-issued licence key and no NovaHost auth session. So the device owns
 * the draft and the server owns enforcement. A fresh install starts from the
 * robot's allowance with nothing enabled, which is the safe direction to be
 * wrong in.
 */

import { supabase } from '../utils/supabaseClient.ts'
import { secStorage } from '../utils/secStorage.js'

const KEY = 'SYMBOL_PLAN'

/** Matches the executor's normalisation exactly. A row written under a
 *  differently-punctuated key is a row the lookup there will miss. */
export function normaliseSymbol(s) {
  return String(s || '').replace(/[^A-Za-z0-9]/g, '').toUpperCase()
}

/**
 * What THIS user's broker calls the instrument.
 *
 * Deliberately NOT normalised — it goes into an order verbatim, and
 * `XAUUSD.m` stripped to `XAUUSDM` is a symbol no broker lists. Only trimmed
 * and reduced to the characters MetaTrader permits. Brokers really do list
 * `.US30.`, `.USTECH.` and `Gold` rather than canonical names, so this field
 * is the difference between an order filling and being rejected.
 *
 * Empty returns null, not '': absent means "I have not said", and the
 * executor falls back to suffix and alias discovery on null. An empty string
 * would send an empty symbol.
 */
export function cleanBrokerSymbol(s) {
  const raw = String(s ?? '').trim().replace(/[^A-Za-z0-9._-]/g, '')
  return raw.length > 0 ? raw : null
}

export const DEFAULT_ROW = { enabled: false, lot: 0.05, max_trades: 2, smart_lot: true, broker_symbol: null }

/** Reads the stored plan. Shape-checked rather than trusted: secStorage fails
 *  closed on a tampered value and returns null, and an older build may have
 *  written a different shape. */
export function loadPlan() {
  const raw = secStorage.getItem(KEY, true)
  const out = {}
  if (raw && typeof raw === 'object') {
    for (const [sym, v] of Object.entries(raw)) {
      if (!v || typeof v !== 'object') continue
      out[normaliseSymbol(sym)] = {
        enabled: v.enabled === true,
        lot: Number(v.lot) || 0,
        max_trades: Number(v.max_trades) || 0,
        smart_lot: v.smart_lot === true,
        broker_symbol: cleanBrokerSymbol(v.broker_symbol),
      }
    }
  }
  return out
}

export function savePlan(plan) {
  secStorage.setItem(KEY, plan)
}

/**
 * Pushes the plan and the risk profile to the executor's ceiling.
 *
 * Only ENABLED symbols are sent. The function prunes anything absent from the
 * payload, which is what makes a de-selected symbol actually stop being
 * tradeable rather than lingering as an enabled row with an old cap.
 *
 * Returns `{ ok, synced, error }` — never throws, because a failed sync must
 * leave the screen usable and say so, not blank it.
 */
export async function syncPlan(plan, risk) {
  const licenseKey = secStorage.getItem('LICENSE_KEY')
  if (!licenseKey) {
    return { ok: false, error: 'No licence key on this device.' }
  }

  const symbols = Object.entries(plan)
    .filter(([, v]) => v.enabled)
    .map(([symbol, v]) => ({
      symbol,
      enabled: true,
      lot: Number(v.lot) || 0,
      max_trades: Number(v.max_trades) || 0,
      smart_lot: v.smart_lot === true,
      broker_symbol: v.broker_symbol || undefined,
    }))

  try {
    const { data, error } = await supabase.functions.invoke('sync-symbol-config', {
      body: {
        license_key: licenseKey,
        balance: Number(risk?.balance) || 0,
        currency: risk?.currency || 'USD',
        risk_percent: Number(risk?.riskPercent) || 0,
        risk_trades: Number(risk?.riskTrades) || 1,
        smart_lot_size: Number(risk?.smartLot) || 0,
        symbols,
      },
    })
    if (error) throw error
    if (!data?.success) throw new Error(data?.error || 'Sync refused.')
    return { ok: true, synced: Number(data.synced) || 0 }
  } catch (err) {
    console.warn('[symbolPlan] sync failed:', err)
    return { ok: false, error: err?.message || 'Could not reach the server.' }
  }
}
